export function getActiveItemCategory(category: string, subcategory?: string): (typeof activeItemCategories)[number] {
  const pair = canonicalizeItemCategoryPair(category, subcategory ?? '')
  if (activeItemCategories.includes(pair.category as (typeof activeItemCategories)[number])) {
    return pair.category as (typeof activeItemCategories)[number]
  }
  if (pair.category === '出行' && pair.subcategory === '自行车') return '运动'
  return '日用'
}

export function getCategoryGroups(customSubcategories: CustomSubcategory[] = []): CategoryGroup[] {
  const canonicalCustom = customSubcategories.map((item) => ({
    ...item,
    category: canonicalizeItemCategoryPair(item.category, item.name).category,
  }))
  return categoryGroups.map((group) => {
    const customItems = canonicalCustom
      .filter((item) => item.category === group.name)
      .filter((item) => item.name.trim())


    return {
      name: group.name,
      // Built-in artwork is tied to its kind. Uncovered custom kinds use text,
      // while historical icon choices stay in settings for backup compatibility.
      items: [
        ...group.items,
        ...customItems
          .filter((item) => !group.items.some((builtIn) => builtIn.name === item.name))
          .map((item) => ({ name: item.name, emoji: item.emoji })),
      ],
    }
  })
}

export function getSelectableCategoryGroups(customSubcategories: CustomSubcategory[] = []): CategoryGroup[] {
  const groups = getCategoryGroups(customSubcategories)
  return activeItemCategories.map((name) => {
    const group = groups.find((entry) => entry.name === name)!
    return {
      ...group,
      items: group.items.filter((item) => !legacyOnlyItemNames.has(item.name)
        || customSubcategories.some((custom) => canonicalizeItemCategoryPair(custom.category, custom.name).category === name
          && custom.name === item.name)),
    }
  })
}

export function getDefaultSubcategory(category: Category): Subcategory {
  return categoryGroups.find((group) => group.name === category)?.items[0].name ?? defaultSubcategory
}

export function getSubcategoryDisplayName(category: Category, subcategory: Subcategory, customSubcategories: CustomSubcategory[] = []) {
  if ((category === '家电' || String(category) === '家居') && subcategory === '其他家电') return '其他家居'
  if (category === '数码' && subcategory === '游戏设备') return '游戏手柄'
  if (category === '数码' && subcategory === '存储设备'
    && !customSubcategories.some((item) => item.category === category && item.name === subcategory)) return '移动硬盘'
  if (category === '穿戴' && subcategory === '鞋靴') return '鞋'
  if (category === '穿戴' && subcategory === '箱包') return '包'
  return subcategory
}

