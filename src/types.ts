// Only explicitly known source pairs move. A same-named kind in any other
// category retains its identity, including historical custom categories.
export function canonicalizeItemCategoryPair(category: string, subcategory: string) {
  const categoryKey = category === '家居' ? '家电' : category === '其他' ? '日用' : category
  const name = subcategory.trim()
  const moves = Object.hasOwn(itemCategoryMoves, categoryKey)
    ? itemCategoryMoves[categoryKey as Category] : undefined
  return {
    category: moves && Object.hasOwn(moves, name) ? moves[name] : categoryKey as Category,
    subcategory: name,
  }
}

