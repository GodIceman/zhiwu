export function getCategoryGroups(customSubcategories: CustomSubcategory[] = []): CategoryGroup[] {
  return categoryGroups.map((group) => {
    const customItems = customSubcategories
      .filter((item) => item.category === group.name)
      .filter((item) => item.name.trim())
      .filter((item) => !group.items.some((builtIn) => builtIn.name === item.name))

    return {
      name: group.name,
      items: [...group.items, ...customItems].map((item) => ({
        name: item.name,
        emoji: item.emoji,
        iconKey: 'iconKey' in item ? item.iconKey : undefined,
      })),
    }
  })
}

export function getDefaultSubcategory(category: Category): Subcategory {
  return categoryGroups.find((group) => group.name === category)?.items[0].name ?? defaultSubcategory
}

export function getSubcategoryMeta(subcategory: Subcategory, customSubcategories: CustomSubcategory[] = []) {
  for (const group of getCategoryGroups(customSubcategories)) {
    const item = group.items.find((candidate) => candidate.name === subcategory)

    if (item) {
      return {
        category: group.name,
        name: item.name,
        emoji: item.emoji,
        iconKey: 'iconKey' in item ? item.iconKey : undefined,
      }
    }
  }

  return {
    category: defaultCategory,
    name: defaultSubcategory,
    emoji: '💻',
    iconKey: undefined,
  }
}

export function normalizeCategoryPair(category: string, subcategory?: string) {
  const directGroup = categoryGroups.find((group) => group.name === category)

  if (directGroup) {
    const normalizedSubcategory = subcategory?.trim()
    const migratedSubcategory = normalizedSubcategory ? legacyCategoryMap[normalizedSubcategory] : undefined

    if (migratedSubcategory?.category === directGroup.name) {
      return migratedSubcategory
    }

    return {
      category: directGroup.name,
      subcategory: normalizedSubcategory || directGroup.items[0].name,
    }
  }

  const legacy = legacyCategoryMap[category]
  if (legacy) return legacy

  const subcategoryMeta = categoryGroups
    .flatMap((group) => group.items.map((item) => ({ category: group.name, item })))
    .find(({ item }) => item.name === subcategory)

  if (subcategoryMeta) {
    return {
      category: subcategoryMeta.category,
      subcategory: subcategoryMeta.item.name,
    }
  }

  return { category: '其他', subcategory: '待分类' } satisfies {
    category: Category
    subcategory: Subcategory
  }
}

